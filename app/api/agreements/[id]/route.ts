import { buildAgreement } from "@/lib/agreement";
import { currentUser } from "@/lib/auth";
import { db } from "@/lib/db";
import { PdfDoc } from "@/lib/pdf";
import { clientById, freelancerById } from "@/lib/queries";

const PURPLE: [number, number, number] = [0.54, 0.22, 0.96];
const MUTED: [number, number, number] = [0.46, 0.46, 0.46];

export async function GET(_: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const user = await currentUser();
  if (!user) return new Response("Sign in to download the agreement.", { status: 401 });
  const data = db();
  const project = data.projects.find((p) => p.id === id);
  if (!project || (project.clientId !== user.id && project.freelancerId !== user.id && user.role !== "admin")) return new Response("Agreement not found", { status: 404 });
  const a = buildAgreement(project, { client: clientById(project.clientId, data)?.displayName ?? "Client", freelancer: freelancerById(project.freelancerId, data)?.user.name ?? "Freelancer" });

  const doc = new PdfDoc((page, n) => {
    page.box(0, 806, 595, 36, PURPLE);
    page.text(56, 819, "FindRight", { size: 14, bold: true, color: [1, 1, 1] });
    page.text(539, 819, `${a.ref} - page ${n}`, { size: 9, color: [0.93, 0.89, 1], align: "right" });
    page.text(56, 40, "Generated by FindRight. Payments in this build are simulated.", { size: 8, color: MUTED });
    return 770;
  });

  doc.paragraph(a.title, { size: 18, bold: true, gap: 2 });
  doc.paragraph(`${a.ref} - ${a.date} - ${a.status}`, { size: 9.5, color: MUTED, gap: 12 });
  for (const [k, v] of a.parties) doc.paragraph(`${k}: ${v}`, { size: 10.5, bold: k === "Project", gap: 2 });
  doc.y -= 10;

  a.sections.forEach((s, i) => {
    doc.ensure(48);
    doc.page.line(doc.left, doc.y + 12, doc.right, doc.y + 12);
    doc.paragraph(`${i + 1}. ${s.heading}`, { size: 12, bold: true, color: PURPLE, gap: 4 });
    s.paragraphs?.forEach((p) => doc.paragraph(p));
    s.bullets?.forEach((b) => doc.paragraph(`- ${b}`, { indent: 10, gap: 2 }));
    if (s.table) {
      const cols = [doc.left, doc.left + 190, doc.left + 260, doc.left + 370];
      doc.ensure(18 * (s.table.rows.length + 1) + 8);
      doc.page.box(doc.left, doc.y - 5, doc.right - doc.left, 18, [0.97, 0.95, 1]);
      s.table.head.forEach((h, c) => doc.page.text(cols[c]! + 6, doc.y, h, { size: 9.5, bold: true }));
      doc.y -= 18;
      for (const row of s.table.rows) {
        row.forEach((cell, c) => doc.page.text(cols[c]! + 6, doc.y, cell, { size: 9.5 }));
        doc.y -= 16;
      }
      doc.y -= 6;
    }
    doc.y -= 6;
  });

  doc.ensure(90);
  doc.page.line(doc.left, doc.y + 12, doc.right, doc.y + 12);
  doc.paragraph("Acceptance", { size: 12, bold: true, color: PURPLE, gap: 4 });
  for (const [k, v] of a.acceptance) doc.paragraph(`${k}: ${v}`, { gap: 2 });

  return new Response(doc.toBuffer(), {
    headers: { "Content-Type": "application/pdf", "Content-Disposition": `attachment; filename="${a.ref}.pdf"`, "Cache-Control": "private, no-store" },
  });
}
